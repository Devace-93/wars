use wars_sim::ids::*;
use wars_sim::types::*;

fn add(target: Target, attr: Attr, value: i32) -> Effect {
    Effect::Add {
        target,
        attr,
        value,
    }
}
fn mul(target: Target, attr: Attr, pct: i32) -> Effect {
    Effect::Mul { target, attr, pct }
}
fn obj(k: &str) -> Target {
    Target::Object(k.into())
}
fn role(r: Role) -> Target {
    Target::Role(r)
}
fn s(v: &[&str]) -> Vec<String> {
    v.iter().map(|x| x.to_string()).collect()
}

#[allow(clippy::too_many_arguments)]
fn civ(
    key: &str,
    name: &str,
    description: &str,
    uu: &str,
    language: &str,
    bonuses: Vec<Effect>,
    bonus_text: &[&str],
    team_bonus: Vec<Effect>,
    team_text: &str,
    unique_techs: &[&str],
    disabled_techs: &[&str],
    disabled_objects: &[&str],
) -> CivDef {
    CivDef {
        key: key.into(),
        name: name.into(),
        description: description.into(),
        bonuses,
        bonus_text: s(bonus_text),
        team_bonus,
        team_bonus_text: team_text.into(),
        unique_unit: uu.into(),
        unique_unit_elite: format!("elite_{uu}"),
        unique_techs: s(unique_techs),
        disabled_techs: s(disabled_techs),
        disabled_objects: s(disabled_objects),
        language: language.into(),
    }
}

